#!/usr/bin/env python3
"""Produce the rounded rational cells and the corresponding Lean input literals."""
from argparse import ArgumentParser
from fractions import Fraction as F
from math import isqrt
from pathlib import Path

P = F(314159, 100000)
Q = F(314160, 100000)
SCALE = 10_000_000
CHUNK_SIZE = 8
FIELDS = (
    "index", "a", "b", "rLo", "rHi", "rho", "lambda",
    "rightHalves", "lossHalves", "costHalves", "loss", "cost",
    "invD", "expCost", "error44", "drift", "phase49",
)


def up(x):
    x = F(x)
    return F(-((-x.numerator * SCALE) // x.denominator), SCALE)


def down(x):
    return -up(-x)


def upper_root(x):
    floor = isqrt(x.numerator * SCALE**2 // x.denominator)
    candidate = F(floor, SCALE)
    return candidate + F(candidate**2 < x, SCALE)


def taylor(x, degree):
    """Evaluate the truncated exponential by Horner's rule."""
    result = F(1)
    for j in range(degree, 0, -1):
        result = 1 + x * result / j
    return result


def bound_exp(x):
    halves = 0
    while x > F(1, 4):
        halves += 1
        x /= 2
    tail_term = F(1)
    for j in range(1, 14):
        tail_term *= x / j
    result = up(taylor(x, 12) + tail_term / (1 - x / 14))
    for _ in range(halves):
        result = up(result * result)
    return result, halves


def cell(index):
    a, b = F(index, 8), F(index + 1, 8)
    exp_right, right_halves = bound_exp(b)
    rlo, rhi = down(1 / exp_right), up(1 / taylor(a, 64))
    hlo, hhi = (r / (1 + r)**2 for r in (rlo, rhi))
    vhi = (1 - rlo) / (1 + rlo)
    m2 = up(hhi)
    m3 = up(hhi * vhi)
    m4 = up(hhi * max(abs(1 - 6*hlo), abs(1 - 6*hhi)))
    m5 = up(hhi * vhi * max(abs(1 - 12*hlo), abs(1 - 12*hhi)))
    coeffs = (up(rhi / (1 + rhi)), up(m2 / 2), up(m3 / 6), up(m4 / 24))
    b1, b2, b3, b4 = coeffs
    rho = upper_root(b*b + Q*Q)
    re2_lo = a*a - Q*Q
    re3_lo = a**3 - 3*Q*Q*b
    re4_lo = a**4 - 6*Q*Q*b*b + P**4
    re4_hi = b**4 - 6*P*P*a*a + Q**4
    fourth = max(abs(re4_lo), abs(re4_hi))
    if 6*hlo >= 1:
        fourth = max(0, re4_hi)
    elif 6*hhi <= 1:
        fourth = max(0, -re4_lo)
    loss = up(max(0, -re2_lo)*b2 + max(0, -re3_lo)*b3 + fourth*b4)
    inv_d, loss_halves = bound_exp(loss)
    drift = up((m2*rho**3 + m3*rho**4/2 + m4*rho**5/6 + m5*rho**6/24) / P)
    reciprocal_s = up(rho / P)
    candidates = []
    for numerator in range(21, 61):
        lam = F(numerator, 20)
        if lam**2 * (b*b + P*P) > b*b + 9*P*P:
            continue
        radius = lam * rho
        cost = up(sum(coefficient * radius**i for i, coefficient in enumerate(coeffs, 1)))
        exp_cost, cost_halves = bound_exp(cost)
        residue = max(rho, lam*rho**2 / (2*P*P))
        error = up(residue * exp_cost * inv_d * reciprocal_s / lam**44)
        candidates.append((error, lam, cost, exp_cost, cost_halves))
    error, lam, cost, exp_cost, cost_halves = min(candidates)
    phase = up((3*error + (2 + error)*drift/49) / 2)
    return (
        index, a, b, rlo, rhi, rho, lam, right_halves, loss_halves, cost_halves,
        loss, cost, inv_d, exp_cost, error, drift, phase,
    )


def lean_literal(value):
    if value.denominator == 1:
        return str(value)
    return f"({value.numerator} / {value.denominator})"


def lean_source(rows):
    lines = [
        "import LongCycleFinite.K5CompactCert.Checks",
        "",
        "/-! Generated by fixed-five-effective/k5-cell-cert/generate.py. -/",
        "",
        "namespace LongCycleFinite.K5CompactCert",
        "",
    ]
    for chunk, first in enumerate(range(0, len(rows), CHUNK_SIZE)):
        lines.append(f"def chunk{chunk} : List Cell := [")
        for offset, row in enumerate(rows[first:first + CHUNK_SIZE]):
            proof_data = [lean_literal(value) for value in row]
            suffix = "," if offset + 1 < CHUNK_SIZE else ""
            lines.extend([
                "  ⟨" + ", ".join(proof_data[:7]) + ",",
                "    " + ", ".join(proof_data[7:14]) + ",",
                "    " + ", ".join(proof_data[14:]) + "⟩" + suffix,
            ])
        lines.extend(["]", ""])
    chunks = [f"chunk{i}" for i in range(len(rows) // CHUNK_SIZE)]
    lines.extend([
        "/-- The 88 cells in increasing endpoint order. -/",
        "def cells : List Cell :=",
        "  " + " ++ ".join(chunks[:7]) + " ++",
        "  " + " ++ ".join(chunks[7:]),
        "",
        "end LongCycleFinite.K5CompactCert",
        "",
    ])
    return "\n".join(lines)


def main():
    here = Path(__file__).resolve().parent
    parser = ArgumentParser(description=__doc__)
    parser.add_argument("--tsv", type=Path, default=here / "cells.tsv")
    parser.add_argument("--lean", type=Path, default=here.parents[1] /
                        "formal/LongCycleFinite/K5CompactCert/Data.lean")
    args = parser.parse_args()
    rows = [cell(index) for index in range(88)]
    args.tsv.write_text("\t".join(FIELDS) + "\n" +
                        "".join("\t".join(map(str, row)) + "\n" for row in rows))
    args.lean.write_text(lean_source(rows))
    for name in ("error44", "drift", "phase49"):
        value, index = max((row[FIELDS.index(name)], row[0]) for row in rows)
        print(f"Maximum {name} = {value}, at cell {index}.")
    print(f"Generated {len(rows)} exact rational cells.")


if __name__ == "__main__":
    main()
